def pick_ending(category: str, rng) -> dict:
    """按类别随机挑选一个结局。"""
    pool = ENDINGS.get(category) or ENDINGS["low"]
    return rng.choice(pool)


def make_title(category: str, rng) -> str:
    """生成称号。"""
    pool = TITLES_BY_CATEGORY.get(category) or TITLES_BY_CATEGORY["low"]
    return rng.choice(pool)
