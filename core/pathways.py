def get_pathway(key: str) -> dict:
    return ALL_PATHWAYS[key]


def seq_name(pathway: dict, seq: int) -> str:
    """返回序列显示名：途径有序列表时用具体名，否则泛称。"""
    sequences = pathway.get("sequences")
    if sequences and seq in sequences:
        return sequences[seq]
    return f"序列{seq}"


def seq0_name(pathway: dict) -> str:
    """途径顶点名（序列0 / 外神本身）。"""
    sequences = pathway.get("sequences")
    if sequences and 0 in sequences:
        return sequences[0]
    return pathway["name"]


def seq_stage(seq: int) -> str:
    """返回序列段的池键：low / mid / high。"""
    if seq >= SEQ_LOW[1]:
        return "low"
    if seq >= SEQ_MID[1]:
        return "mid"
    return "high"
